import Foundation

/// User-selectable UI language. `system` follows the OS (English fallback).
enum AppLanguage: String, CaseIterable, Identifiable, Hashable {
    case system
    case en
    case de
    case fr
    case it
    case es
    case pt
    case nl
    case pl
    case ja
    case zhHans

    var id: String { rawValue }

    /// Name shown in the language picker (native).
    var displayName: String {
        switch self {
        case .system: return L10n.t("language.system")
        case .en: return "English"
        case .de: return "Deutsch"
        case .fr: return "Français"
        case .it: return "Italiano"
        case .es: return "Español"
        case .pt: return "Português"
        case .nl: return "Nederlands"
        case .pl: return "Polski"
        case .ja: return "日本語"
        case .zhHans: return "简体中文"
        }
    }

    /// BCP-47 code used for lookup (`system` resolves at runtime).
    var resolvedCode: String {
        switch self {
        case .system:
            let preferred = (Locale.preferredLanguages.first ?? "en").lowercased()
            if preferred.hasPrefix("zh") { return "zh-Hans" }
            let code = String(preferred.prefix(2))
            let supported = ["en", "de", "fr", "it", "es", "pt", "nl", "pl", "ja"]
            return supported.contains(code) ? code : "en"
        case .zhHans: return "zh-Hans"
        default: return rawValue
        }
    }
}

